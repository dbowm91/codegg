#!/usr/bin/env python3
"""Generate Rust source from the curated subagent name pool.

Reads `*.toml` from `assets/subagent-names/` and writes:
  - `src/agent/subagent_names/generated.rs`

Requires Python 3.11+ (uses tomllib from stdlib).

This script owns exactly one output file. It deliberately does NOT generate a
`mod.rs`, unlike `scripts/generate_builtin_agents.py`: that generator owns
`src/agent/builtins/mod.rs` outright, so this module's `mod.rs` is hand-written
and declares the generated submodule itself.

Usage:
    python3 scripts/generate_subagent_names.py           # generate
    python3 scripts/generate_subagent_names.py --check   # verify mode (CI)
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

import tomllib

OUTPUT_GENERATED_RS = "src/agent/subagent_names/generated.rs"

HEADER = "// AUTO-GENERATED by scripts/generate_subagent_names.py — DO NOT EDIT"

# Recognised top-level keys under [[name]].
KNOWN_NAME_KEYS = {"name", "profile", "usefulness", "sprite"}

# A display name becomes a tab label and a row label, so keep it to a single
# word of letters. Numeric suffixes (`Name-2`) are appended by the registry at
# runtime, not written here.
NAME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9]*$")

# Names longer than this get truncated in narrow panels; flag them at author
# time rather than letting layout silently clip.
MAX_NAME_LEN = 24


def _repo_root() -> Path:
    return Path(__file__).resolve().parent.parent


def _format_str_literal(s: str) -> str:
    """Return a Rust string literal expression with proper escaping."""
    escaped = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def _format_option_str_literal(s: str | None) -> str:
    """Return `None` for an absent/blank value, else `Some("...")`."""
    if s is None or s == "":
        return "None"
    return f"Some({_format_str_literal(s)})"


def _validate_name_entry(entry: dict, source: Path) -> list[str]:
    """Validate one [[name]] table. Returns a list of error strings."""
    errors: list[str] = []

    unknown = set(entry.keys()) - KNOWN_NAME_KEYS
    if unknown:
        errors.append(f"{source.name}: unknown keys: {', '.join(sorted(unknown))}")

    if "name" not in entry:
        errors.append(f"{source.name}: [[name]] entry missing required 'name'")
        return errors  # cannot validate the rest without a name

    name = entry["name"]
    if not isinstance(name, str) or not name:
        errors.append(f"{source.name}: 'name' must be a non-empty string")
        return errors

    if not NAME_RE.match(name):
        errors.append(
            f"{source.name}: name '{name}' must be alphanumeric and start with a "
            f"letter (it is rendered as a tab and row label)"
        )
    if len(name) > MAX_NAME_LEN:
        errors.append(
            f"{source.name}: name '{name}' exceeds {MAX_NAME_LEN} characters and "
            f"will clip in narrow panels"
        )

    for key in ("profile", "usefulness", "sprite"):
        if key in entry and not isinstance(entry[key], str):
            errors.append(f"{source.name}: name '{name}': '{key}' must be a string")

    return errors


def _build_entry(entry: dict) -> str:
    """Return a Rust `SubagentName { ... }` expression string."""
    name = entry["name"]
    profile = entry.get("profile", "")
    usefulness = entry.get("usefulness", "")
    sprite = entry.get("sprite") or None

    return (
        "    SubagentName {\n"
        f"        name: {_format_str_literal(name)},\n"
        f"        profile: {_format_str_literal(profile)},\n"
        f"        usefulness: {_format_str_literal(usefulness)},\n"
        f"        sprite: {_format_option_str_literal(sprite)},\n"
        "    }"
    )


def _build_generated_rs(entries: list[dict]) -> str:
    """Return the full content of generated.rs."""
    items = ",\n".join(_build_entry(e) for e in entries)
    return (
        f"{HEADER}\n"
        "\n"
        "/// One entry in the curated pool of human-readable subagent names.\n"
        "///\n"
        "/// A name is held only while its subagent is active. When the pool entry\n"
        "/// is already taken, the registry appends the next free numeric variant\n"
        "/// (`Name`, `Name-2`, `Name-3`, ...) at assignment time; the numeric\n"
        "/// suffix is never stored here.\n"
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n"
        "pub struct SubagentName {\n"
        "    /// Display name assigned to a subagent identifier.\n"
        "    pub name: &'static str,\n"
        "    /// Character description. Carried for later use as subagent context;\n"
        "    /// not rendered by the TUI today.\n"
        "    pub profile: &'static str,\n"
        "    /// Candid operational guidance. Not rendered by the TUI today.\n"
        "    pub usefulness: &'static str,\n"
        "    /// Optional sprite identifier reserved for future TUI use.\n"
        "    /// `None` until a sprite is assigned in the TOML source.\n"
        "    pub sprite: Option<&'static str>,\n"
        "}\n"
        "\n"
        "/// The full curated name pool, ordered as authored in the TOML source.\n"
        "pub const SUBAGENT_NAMES: &[SubagentName] = &[\n"
        f"{items},\n"
        "];\n"
        "\n"
        "/// Borrow the curated subagent name pool.\n"
        "pub fn subagent_names() -> &'static [SubagentName] {\n"
        "    SUBAGENT_NAMES\n"
        "}\n"
    )


def load_and_validate(repo_root: Path) -> tuple[list[dict], list[str]]:
    """Load every name TOML, validate, and return (entries, all_errors)."""
    name_dir = repo_root / "assets" / "subagent-names"

    if not name_dir.is_dir():
        return [], [f"subagent name directory not found: {name_dir}"]

    toml_files = sorted(name_dir.glob("*.toml"))
    if not toml_files:
        return [], [f"no .toml files found in {name_dir}"]

    all_errors: list[str] = []
    entries: list[dict] = []
    seen_names: set[str] = set()

    for toml_path in toml_files:
        with open(toml_path, "rb") as f:
            data = tomllib.load(f)

        unknown_top = set(data.keys()) - {"name"}
        if unknown_top:
            all_errors.append(
                f"{toml_path.name}: unknown top-level tables: "
                f"{', '.join(sorted(unknown_top))}"
            )

        raw_entries = data.get("name", [])
        if not isinstance(raw_entries, list):
            all_errors.append(f"{toml_path.name}: 'name' must be an array of tables")
            continue

        for raw in raw_entries:
            all_errors.extend(_validate_name_entry(raw, toml_path))
            name = raw.get("name")
            if not isinstance(name, str) or not name:
                continue
            if name in seen_names:
                all_errors.append(
                    f"{toml_path.name}: duplicate subagent name '{name}' "
                    f"(names must be unique in the pool)"
                )
                continue
            seen_names.add(name)
            entries.append(raw)

    return entries, all_errors


def generate(repo_root: Path) -> None:
    """Write generated.rs from the TOML source."""
    entries, errors = load_and_validate(repo_root)

    if errors:
        print("Schema validation errors:", file=sys.stderr)
        for err in errors:
            print(f"  {err}", file=sys.stderr)
        sys.exit(1)

    print(f"Generating from {len(entries)} subagent name(s)...")

    out = repo_root / OUTPUT_GENERATED_RS
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(_build_generated_rs(entries), encoding="utf-8")
    print(f"Wrote {out}")


def check(repo_root: Path) -> None:
    """Compare generated output against the checked-in file. Exit 1 on drift."""
    entries, errors = load_and_validate(repo_root)

    if errors:
        print("Schema validation errors:", file=sys.stderr)
        for err in errors:
            print(f"  {err}", file=sys.stderr)
        sys.exit(1)

    print(f"Checking {len(entries)} subagent name(s)...")

    expected = _build_generated_rs(entries)
    out = repo_root / OUTPUT_GENERATED_RS
    drift = False

    if out.is_file():
        actual = out.read_text(encoding="utf-8")
        if actual != expected:
            diff = difflib.unified_diff(
                actual.splitlines(keepends=True),
                expected.splitlines(keepends=True),
                fromfile=OUTPUT_GENERATED_RS,
                tofile=f"{OUTPUT_GENERATED_RS} (expected)",
            )
            print(f"DRIFT in {OUTPUT_GENERATED_RS}:", file=sys.stderr)
            sys.stderr.writelines(diff)
            drift = True
        else:
            print(f"  {OUTPUT_GENERATED_RS}: OK")
    else:
        print(f"  {OUTPUT_GENERATED_RS}: MISSING (run generate)", file=sys.stderr)
        drift = True

    # Determinism check: generate twice, compare.
    entries2, _ = load_and_validate(repo_root)
    if entries != entries2:
        print(
            "DETERMINISM FAILURE: two consecutive loads produced different results",
            file=sys.stderr,
        )
        drift = True

    if drift:
        print("\nRun: python3 scripts/generate_subagent_names.py", file=sys.stderr)
        sys.exit(1)

    print("All checks passed.")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate Rust subagent name source from TOML definitions."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify checked-in output matches TOML definitions (for CI).",
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=None,
        help="Path to the repository root (defaults to parent of scripts/).",
    )
    args = parser.parse_args()

    repo_root: Path = args.repo_root if args.repo_root else _repo_root()
    repo_root = repo_root.resolve()

    if not repo_root.is_dir():
        print(f"Error: repo root does not exist: {repo_root}", file=sys.stderr)
        sys.exit(1)

    try:
        if args.check:
            check(repo_root)
        else:
            generate(repo_root)
    except Exception as exc:
        print(f"Error: {exc}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()