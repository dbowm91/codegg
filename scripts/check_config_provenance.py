#!/usr/bin/env python3
"""Static guard for the generated configuration catalog and provenance surface.

`architecture/config-catalog.md` is generated from `Config` by a test in
`crates/codegg-config/src/config_catalog.rs`, and the merge strategies it lists
are declared in `crates/codegg-config/src/provenance.rs`. Three files have to
agree, and nothing in the compiler makes them:

  schema.rs  the fields of `Config`
  provenance.rs  the declared strategy for each section, and the credential
                 classification the dump redacts with
  architecture/config-catalog.md  the generated document an operator reads

This guard fails on four classes of drift.

- **hand-edited catalog** — the first line must be the generator's header,
  character for character, and the generator's own header constant must be the
  same string. A file whose rows happen to match but whose header was rewritten
  is rejected, because "do not edit this" is a property of the artifact.
- **a row without a strategy** — every row's merge shape, attribution rule and
  combine depth must be a declared value, and the shape and rule must agree
  (a concatenation is attributed by `concatenate`, nothing else is).
- **a key in one place and not the other** — the catalog's keys, the declared
  table's sections and `Config`'s fields must be the same set.
- **a credential with a value** — a captured dump fixture must print `(set)` or
  `(unset)` for a credential-shaped key, never the value; and every schema field
  whose name is credential-shaped must be declared in `CREDENTIAL_FIELDS` with
  the rule that redacts it, so an unmarked credential field is a guard failure
  rather than a disclosure.

A fifth check covers the subcommand: once `Commands::Config` exists in
`src/main.rs`, its help must name `--provenance` and `--format`. Until then the
check reports PENDING instead of failing, because the catalog is useful before
the command lands and a red guard that everyone ignores protects nothing. The
self-test injects the variant and proves the check rejects a help text that
omits the flags.

Run with `--self-test` to prove every injection is rejected.

Exit code 0 if all checks pass, 1 if any fail.
"""

from __future__ import annotations

import json
import re
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import check_config_merge_coverage as merge_guard  # noqa: E402  (path is set above)

REPO_ROOT = Path(__file__).resolve().parent.parent
CONFIG_SRC_DIR = REPO_ROOT / "crates" / "codegg-config" / "src"
SCHEMA_MODULE = CONFIG_SRC_DIR / "schema.rs"
PROVENANCE_MODULE = CONFIG_SRC_DIR / "provenance.rs"
CATALOG_MODULE = CONFIG_SRC_DIR / "config_catalog.rs"
CATALOG_PATH = REPO_ROOT / "architecture" / "config-catalog.md"
MAIN_MODULE = REPO_ROOT / "src" / "main.rs"
FIXTURE_DIR = REPO_ROOT / "crates" / "codegg-config" / "fixtures"

# The exact first line the generator writes. Kept here as a literal *and*
# compared against the generator's own constant, so the two cannot drift.
EXPECTED_HEADER = (
    "<!-- AUTO-GENERATED by crates/codegg-config/src/config_catalog.rs — DO NOT EDIT -->"
)
EXPECTED_UPDATE_COMMAND = "CODEGG_UPDATE_CONFIG_CATALOG=1 cargo test -p codegg-config config_catalog"

SHAPES = {
    "whole-value",
    "whole-value-with-inherit",
    "field-by-field",
    "union-of-keys",
    "concatenate",
}
RULES = {"last-containing", "concatenate"}
DEPTHS = {"0", "1", "2"}

# A redacted value, in either format.
REDACTED = {"(set)", "(unset)"}


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _string_const(source: str, name: str) -> list[str]:
    """The string items of a `pub const NAME: &[&str] = &[..]` block."""
    match = re.search(rf"pub const {name}\s*:\s*&\[&str\]\s*=\s*&\[(.*?)\];", source, re.S)
    if not match:
        raise ValueError(f"`pub const {name}: &[&str]` not found")
    return re.findall(r'"([^"]+)"', match.group(1))


def _pair_table(source: str, name: str) -> list[tuple[str, str, str]]:
    """The triples of a `pub const NAME: &[(&str, &str, &str)] = &[..]` block."""
    match = re.search(
        rf"pub const {name}\s*:\s*&\[\(&str,\s*&str,\s*&str\)\]\s*=\s*&\[(.*?)\];",
        source,
        re.S,
    )
    if not match:
        raise ValueError(f"`pub const {name}: &[(&str, &str, &str)]` not found")
    # rustfmt may break a tuple across lines and leave a trailing comma, so the
    # entry pattern is whitespace- and comma-tolerant.
    return re.findall(
        r'\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,?\s*\)',
        match.group(1),
        re.S,
    )


def catalog_body(text: str) -> str:
    """The `## Sections` table, without its header rows."""
    start = text.find("## Sections")
    if start == -1:
        return ""
    rows = []
    for line in text[start:].splitlines():
        line = line.strip()
        if not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if len(cells) < 2 or set(cells[0]) <= {"-", ":"}:
            continue
        if cells[0] == "Key":
            continue
        rows.append(cells)
    return "\n".join("|".join(cells) for cells in rows)


def catalog_rows(text: str) -> list[list[str]]:
    """The catalog's rows as cell lists."""
    body = catalog_body(text)
    return [row.split("|") for row in body.splitlines() if row]


def catalog_keys(text: str) -> list[str]:
    """The catalog's `Key` column, without the backticks."""
    return [row[0].strip("`") for row in catalog_rows(text)]


def section_for_key(key: str) -> str:
    """The schema field a serialized key belongs to.

    Mirrors `provenance::strategy_for`: `$schema` is the serde rename of the
    `schema` field, and `$`-prefixed keys are serde's meta-key convention.
    """
    return key[1:] if key.startswith("$") else key


def header_problems(catalog_module_source: str, catalog_text: str) -> list[str]:
    """The catalog must carry the generator's header, not a hand-written one."""
    problems: list[str] = []
    match = re.search(r'GENERATED_HEADER\s*:\s*&str\s*=\s*"([^"]+)"', catalog_module_source)
    if not match:
        problems.append("`GENERATED_HEADER` not found in config_catalog.rs")
    elif match.group(1) != EXPECTED_HEADER:
        problems.append(
            "config_catalog.rs writes a different header than this guard requires: "
            f"{match.group(1)!r}"
        )
    update = re.search(r'UPDATE_COMMAND\s*:\s*&str\s*=\s*"([^"]+)"', catalog_module_source)
    if not update:
        problems.append("`UPDATE_COMMAND` not found in config_catalog.rs")
    elif update.group(1) != EXPECTED_UPDATE_COMMAND:
        problems.append(
            "config_catalog.rs writes a different update command than this guard requires: "
            f"{update.group(1)!r}"
        )

    lines = catalog_text.splitlines()
    if not lines:
        return problems + ["the catalog is empty"]
    if lines[0] != EXPECTED_HEADER:
        problems.append(
            f"line 1 is not the generated header: {lines[0]!r}\n"
            f"      expected: {EXPECTED_HEADER!r}\n"
            "      A hand-edited catalog is rejected even when its rows match."
        )
    if len(lines) < 2 or EXPECTED_UPDATE_COMMAND not in lines[1]:
        problems.append(
            f"line 2 does not name the regeneration command: {lines[1] if len(lines) > 1 else ''!r}"
        )
    return problems


def row_problems(catalog_text: str) -> list[str]:
    """Every row must carry a declared strategy."""
    problems: list[str] = []
    seen: set[str] = set()
    keys = catalog_keys(catalog_text)
    if not keys:
        return ["the catalog has no section rows"]
    for cells in catalog_rows(catalog_text):
        key = cells[0].strip("`")
        if key in seen:
            problems.append(f"`{key}` is listed twice")
        seen.add(key)
        if len(cells) < 6:
            problems.append(f"`{key}` has {len(cells)} cells; the table declares 6")
            continue
        shape, rule, depth = cells[1], cells[2], cells[3]
        if shape not in SHAPES:
            problems.append(f"`{key}` has no declared merge shape: {shape!r}")
        if rule not in RULES:
            problems.append(f"`{key}` has no declared attribution rule: {rule!r}")
        if depth not in DEPTHS:
            problems.append(f"`{key}` has no declared combine depth: {depth!r}")
        if rule in RULES and shape in SHAPES:
            concatenates = shape == "concatenate"
            if concatenates != (rule == "concatenate"):
                problems.append(
                    f"`{key}` declares shape `{shape}` with rule `{rule}`; only a "
                    "concatenating section is attributed by `concatenate`"
                )
    return problems


def coverage_problems(
    catalog_text: str, schema_source: str, provenance_source: str
) -> list[str]:
    """The catalog, the declared table and `Config` must name the same sections."""
    problems: list[str] = []
    try:
        declared = {entry["section"] for entry in merge_guard.strategy_entries(provenance_source)}
        fields = set(merge_guard.config_fields(schema_source))
    except ValueError as exc:
        return [f"cannot read the strategy table: {exc}"]
    catalog = {section_for_key(key) for key in catalog_keys(catalog_text)}

    for label, left, right in (
        ("the catalog and the strategy table", catalog, declared),
        ("the strategy table and `Config`", declared, fields),
    ):
        missing = sorted(right - left)
        extra = sorted(left - right)
        if missing:
            problems.append(f"{label} disagree: {missing} is missing from the other side")
        if extra:
            problems.append(f"{label} disagree: {extra} is not in the other side")
    return problems


def credential_chars(provenance_source: str) -> tuple[set[str], set[str]]:
    """The declared credential names and container segments."""
    names = {name.lower() for name in _string_const(provenance_source, "CREDENTIAL_NAMES")}
    containers = {
        name.lower() for name in _string_const(provenance_source, "CREDENTIAL_CONTAINERS")
    }
    return names, containers


def is_credential_key(key: str, names: set[str], containers: set[str]) -> bool:
    """Whether this key path names a credential, by the declared rules."""
    segments = key.split(".")
    if segments[-1].lower() in names:
        return True
    return any(segment.lower() in containers for segment in segments)


def fixture_problems(text: str, suffix: str, names: set[str], containers: set[str]) -> list[str]:
    """A captured dump must never carry a credential's value."""
    problems: list[str] = []
    if suffix == ".json":
        try:
            entries = json.loads(text)
        except json.JSONDecodeError as exc:
            return [f"the JSON fixture does not parse: {exc}"]
        if not isinstance(entries, list):
            return ["the JSON fixture is not an array of entries"]
        for entry in entries:
            if not isinstance(entry, dict) or "path" not in entry:
                continue
            key = str(entry["path"])
            value = entry.get("value")
            if is_credential_key(key, names, containers) and value not in REDACTED:
                problems.append(f"`{key}` carries a value ({value!r}) in a captured dump")
            for shadowed in entry.get("shadowed") or []:
                if not isinstance(shadowed, dict):
                    continue
                if is_credential_key(key, names, containers):
                    if shadowed.get("value") not in REDACTED:
                        problems.append(
                            f"`{key}` shadowed value ({shadowed.get('value')!r}) is not redacted"
                        )
        return problems

    for line in text.splitlines():
        if " = " not in line:
            continue
        key = line.split(" = ", 1)[0].strip()
        if key.startswith("shadowed: "):
            key = key[len("shadowed: ") :]
        if "." not in key or " " in key:
            continue
        value = line.split(" = ", 1)[1].strip()
        if is_credential_key(key, names, containers) and value not in REDACTED:
            problems.append(f"`{key}` carries a value ({value!r}) in a captured dump")
    return problems


# Field-name tokens that make a schema field a credential *candidate*. This is a
# detector, not a classifier: the declared `CREDENTIAL_FIELDS` table decides, and
# the guard requires every candidate to be in it.
WHOLE_NAME_CANDIDATES = {
    "api_key",
    "apikey",
    "api-key",
    "encrypted_api_key",
    "private_key",
    "privatekey",
    "client_secret",
    "clientsecret",
    "auth_token",
    "access_token",
    "refresh_token",
    "id_token",
    "auth",
    "env",
    "environment",
    "headers",
    "options",
    "oauth",
}
PART_CANDIDATES = {"secret", "token", "password", "passwd", "credential", "credentials"}


def is_candidate_field(name: str) -> bool:
    """Whether a schema field name is credential-shaped."""
    lowered = name.lower()
    if lowered in WHOLE_NAME_CANDIDATES:
        return True
    return any(part in PART_CANDIDATES for part in lowered.split("_"))


def credential_field_problems(schema_source: str, provenance_source: str) -> list[str]:
    """Every credential-shaped schema field must declare how it is redacted."""
    problems: list[str] = []
    try:
        declared = _pair_table(provenance_source, "CREDENTIAL_FIELDS")
        names, containers = credential_chars(provenance_source)
    except ValueError as exc:
        return [f"cannot read the credential declaration: {exc}"]

    definitions = merge_guard.struct_definitions([("schema.rs", schema_source)])
    candidates = {
        (struct, field)
        for struct, fields in definitions.items()
        for field, _field_type in fields
        if is_candidate_field(field)
    }
    declared_pairs = {(owner, field) for owner, field, _cause in declared}

    for owner, field, cause in declared:
        if cause == "name":
            if field.lower() not in names:
                problems.append(
                    f"`{owner}.{field}` is declared by name but the name is not listed"
                )
        elif cause.startswith("container:"):
            segment = cause.split(":", 1)[1].lower()
            if segment not in containers:
                problems.append(
                    f"`{owner}.{field}` is declared as container `{segment}` but no "
                    "such container is redacted"
                )
        elif cause not in {"open-map", "not-a-credential"}:
            problems.append(f"`{owner}.{field}` has an unknown cause `{cause}`")

    for struct, field in sorted(candidates - declared_pairs):
        problems.append(
            f"`{struct}.{field}` is credential-shaped but is not declared in "
            "CREDENTIAL_FIELDS; the dump would print its value"
        )
    for struct, field in sorted(declared_pairs - candidates):
        problems.append(
            f"`{struct}.{field}` is declared in CREDENTIAL_FIELDS but is not a "
            "credential-shaped field in the schema"
        )
    return problems


def has_config_command(main_source: str) -> bool:
    """Whether `Commands::Config` is declared."""
    header = re.search(r"enum Commands\s*\{", main_source)
    if not header:
        return False
    try:
        body = merge_guard._braced_block(main_source, header)
    except ValueError:
        return False
    return re.search(r"\bConfig\s*\{", body) is not None


def subcommand_problems(main_source: str) -> list[str]:
    """Once `Commands::Config` exists, its help must name the flags."""
    problems: list[str] = []
    header = re.search(r"enum Commands\s*\{", main_source)
    if not header:
        return problems
    try:
        body = merge_guard._braced_block(main_source, header)
    except ValueError as exc:
        return [f"cannot read `enum Commands`: {exc}"]
    config = re.search(r"\bConfig\s*\{", body)
    if not config:
        return problems
    try:
        variant = merge_guard._braced_block(body, config)
    except ValueError as exc:
        return [f"cannot read `Commands::Config`: {exc}"]

    # Clap derives a variant's help from the doc comment and attributes *above*
    # it, so those lines are part of the surface this check covers.
    doc: list[str] = []
    for line in reversed(body[: config.start()].splitlines()):
        stripped = line.strip()
        if not stripped:
            # The indentation before the variant name is not a separator.
            continue
        if stripped.startswith("///") or stripped.startswith("#["):
            doc.append(stripped)
            continue
        break

    help_text = "\n".join([*doc, variant])
    for flag in ("--provenance", "--format"):
        if flag not in help_text:
            problems.append(
                f"`Commands::Config` exists but its help never names `{flag}`; the "
                "subcommand and the catalog must describe the same surface"
            )
    return problems


def check_catalog_exists() -> bool:
    if not CATALOG_PATH.is_file():
        print(
            "  FAIL: architecture/config-catalog.md is missing; generate it with "
            f"`{EXPECTED_UPDATE_COMMAND}`"
        )
        return False
    return True


def check_header() -> bool:
    problems = header_problems(_read(CATALOG_MODULE), _read(CATALOG_PATH))
    return _report(problems, "the catalog carries its generated header")


def check_rows() -> bool:
    problems = row_problems(_read(CATALOG_PATH))
    return _report(problems, "every catalog row declares a strategy")


def check_coverage() -> bool:
    problems = coverage_problems(
        _read(CATALOG_PATH), _read(SCHEMA_MODULE), _read(PROVENANCE_MODULE)
    )
    return _report(problems, "the catalog, the table and `Config` name the same sections")


def check_credential_fields() -> bool:
    problems = credential_field_problems(_read(SCHEMA_MODULE), _read(PROVENANCE_MODULE))
    return _report(problems, "every credential-shaped schema field is declared")


def check_fixtures() -> bool:
    names, containers = credential_chars(_read(PROVENANCE_MODULE))
    fixtures = sorted(FIXTURE_DIR.glob("provenance-*")) if FIXTURE_DIR.is_dir() else []
    if not fixtures:
        print(
            "  FAIL: no captured dump fixture under "
            f"{FIXTURE_DIR.relative_to(REPO_ROOT)}; the redaction check would be vacuous"
        )
        return False
    problems: list[str] = []
    for fixture in fixtures:
        if fixture.suffix not in {".txt", ".json"}:
            continue
        problems.extend(
            f"{fixture.name}: {problem}"
            for problem in fixture_problems(
                fixture.read_text(encoding="utf-8"), fixture.suffix, names, containers
            )
        )
    return _report(problems, "no captured dump carries a credential value")


def check_subcommand_help() -> bool:
    if not MAIN_MODULE.is_file():
        print("  [SKIP] src/main.rs does not exist")
        return True
    main_source = _read(MAIN_MODULE)
    if not has_config_command(main_source):
        print(
            "  [PENDING] `Commands::Config` is not declared yet; the help check "
            "starts enforcing when it lands"
        )
        return True
    return _report(
        subcommand_problems(main_source), "the config subcommand's help names its flags"
    )


def _report(problems: list[str], subject: str) -> bool:
    if problems:
        print(f"  FAIL: {subject}")
        for problem in problems:
            print(f"        - {problem}")
        return False
    return True


def _self_test() -> int:
    """Prove every injection is rejected, and the baseline is green."""
    schema = _read(SCHEMA_MODULE)
    provenance = _read(PROVENANCE_MODULE)
    catalog_module = _read(CATALOG_MODULE)
    catalog = _read(CATALOG_PATH)
    names, containers = credential_chars(provenance)
    main = """enum Commands {
    /// Show the effective configuration: `--provenance` names the winning
    /// layer and `--format json` emits the stable document.
    Config {
        #[command(subcommand)]
        command: ConfigSubcommand,
    },
    Doctor,
}
"""

    cases: list[tuple[str, bool, object]] = []

    def add(description: str, should_pass: bool, problems: list[str], expect: str) -> None:
        if should_pass:
            ok = not problems
        else:
            ok = any(expect in problem for problem in problems)
        cases.append((description, ok, problems))

    # 1. Baseline: the real catalog is green.
    add("the committed catalog passes", True, header_problems(catalog_module, catalog), "")
    add("the committed rows pass", True, row_problems(catalog), "")
    add(
        "the committed catalog covers the schema",
        True,
        coverage_problems(catalog, schema, provenance),
        "",
    )
    add("the committed credential declaration is complete", True, credential_field_problems(schema, provenance), "")
    fixtures = [
        fixture
        for fixture in sorted(FIXTURE_DIR.glob("provenance-*"))
        if fixture.suffix in {".txt", ".json"}
    ]
    add(
        "the committed fixture set is redacted",
        True,
        []
        if fixtures
        else ["no captured dump fixture exists"],
        "",
    )
    add(
        "the committed fixture set is redacted (contents)",
        True,
        [
            problem
            for fixture in fixtures
            for problem in fixture_problems(
                fixture.read_text(encoding="utf-8"), fixture.suffix, names, containers
            )
        ],
        "",
    )

    # 2. Injections.
    lines = catalog.splitlines()
    hand_edited = "\n".join(["# Configuration Catalog", *lines[1:]])
    add(
        "a hand-edited catalog header fails",
        False,
        header_problems(catalog_module, hand_edited),
        "not the generated header",
    )

    falling_out_of_sync = re.search(
        r'GENERATED_HEADER\s*:\s*&str\s*=\s*"([^"]+)"', catalog_module
    ).group(1)
    add(
        "a generator whose header is not the checked one fails",
        False,
        header_problems(catalog_module.replace(falling_out_of_sync, "A different header"), catalog),
        "different header",
    )

    section_rows = [
        line for line in lines if line.startswith("| `") and "|---" not in line
    ]
    no_strategy = "\n".join(
        line if line != section_rows[0] else "| `$schema` |  |  |  | `—` |  |"
        for line in lines
    )
    add(
        "a catalog row with no strategy fails",
        False,
        row_problems(no_strategy),
        "no declared merge shape",
    )

    unknown_key = "\n".join(
        line if line != section_rows[0] else line.replace("`$schema`", "`not_a_key`")
        for line in lines
    )
    add(
        "a catalog key with no schema field fails",
        False,
        coverage_problems(unknown_key, schema, provenance),
        "not in the other side",
    )

    # 3. Fixture injections.
    text_fixture = "== project ==\n  provider.openai.api_key = (set)\n"
    add(
        "a redacted text fixture passes",
        True,
        fixture_problems(text_fixture, ".txt", names, containers),
        "",
    )
    leaked_text = text_fixture.replace("(set)", "sk-live-1234")
    add(
        "a credential value in a text fixture fails",
        False,
        fixture_problems(leaked_text, ".txt", names, containers),
        "carries a value",
    )
    json_fixture = json.dumps(
        [{"path": "provider.openai.api_key", "value": "(set)", "layer": "project", "shadowed": []}]
    )
    add(
        "a redacted JSON fixture passes",
        True,
        fixture_problems(json_fixture, ".json", names, containers),
        "",
    )
    leaked_json = json.dumps(
        [
            {
                "path": "mcp.remote.headers.Authorization",
                "value": "Bearer abc",
                "layer": "project",
                "shadowed": [],
            }
        ]
    )
    add(
        "a credential value in a JSON fixture fails",
        False,
        fixture_problems(leaked_json, ".json", names, containers),
        "carries a value",
    )

    # 4. An unmarked credential field.
    unmarked = schema.replace(
        "pub struct ServerConfig {",
        "pub struct ServerConfig {\n    pub session_token: Option<String>,",
        1,
    )
    add(
        "a credential-shaped field with no declaration fails",
        False,
        credential_field_problems(unmarked, provenance),
        "session_token",
    )
    add(
        "a declaration for no schema field fails",
        False,
        credential_field_problems(
            schema,
            provenance.replace(
                '("ServerConfig", "token", "name"),',
                '("ServerConfig", "token", "name"),\n    ("ServerConfig", "gone_field", "name"),',
            ),
        ),
        "gone_field",
    )

    # 5. The subcommand help.
    add("a subcommand whose help names its flags passes", True, subcommand_problems(main), "")
    add(
        "a subcommand whose help omits --provenance fails",
        False,
        subcommand_problems(main.replace("`--provenance`", "the winning layer")),
        "--provenance",
    )
    add(
        "a tree with no subcommand yet reports nothing",
        True,
        subcommand_problems("enum Commands {\n    Doctor,\n}\n"),
        "",
    )

    failures = 0
    for description, ok, problems in cases:
        detail = "" if ok else f" -> {problems}"
        print(f"  [{'PASS' if ok else 'FAIL'}] self-test: {description}{detail}")
        if not ok:
            failures += 1

    if failures:
        print(f"{failures} self-test case(s) FAILED.")
        return 1
    print("All guard self-test cases passed.")
    return 0


def main() -> int:
    if "--self-test" in sys.argv:
        return _self_test()
    verbose = "--verbose" in sys.argv or "-v" in sys.argv
    checks = [
        ("the generated catalog exists", check_catalog_exists),
        ("the catalog carries its generated header", check_header),
        ("every catalog row declares a strategy", check_rows),
        (
            "the catalog, the strategy table and Config agree",
            check_coverage,
        ),
        (
            "every credential-shaped schema field is declared",
            check_credential_fields,
        ),
        ("no captured dump carries a credential value", check_fixtures),
        ("the config subcommand's help names its flags", check_subcommand_help),
    ]

    results: list[tuple[str, bool]] = []
    for name, check_fn in checks:
        if verbose:
            print(f"CHECK: {name} ... ", end="", flush=True)
        ok = check_fn()  # type: ignore[operator]
        if verbose:
            print("PASS" if ok else "FAIL")
        results.append((name, ok))

    print()
    passed = sum(1 for _, ok in results if ok)
    failed = sum(1 for _, ok in results if not ok)
    for name, ok in results:
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}")
    print(f"\n{passed}/{len(results)} checks passed.")
    if failed:
        print(f"{failed} check(s) FAILED.")
        return 1
    print("All config provenance invariants verified.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
