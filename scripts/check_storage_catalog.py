#!/usr/bin/env python3
"""Structural guard for the generated storage catalog (M006).

`architecture/storage-catalog.md` is produced by running the real migration
chain (`crates/codegg-core/src/session/schema/storage_catalog.rs`). Its
freshness is a Rust test; this guard checks the properties a stale or
hand-edited file would break but a regeneration would not:

  * the generated header and its update command,
  * the declared layout version equals `STORAGE_LAYOUT_VERSION`,
  * every table has an owning module and an introducing migration,
  * no duplicate table and no duplicate column within a table,
  * every `docs/storage-table-owners.toml` entry names a table the catalog
    contains, and every owner path resolves.

`--self-test` injects each defect class in a synthetic catalog and proves the
guard rejects it. Exit code 0 if all checks pass, 1 if any fail.
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CATALOG = REPO_ROOT / "architecture" / "storage-catalog.md"
OWNER_MAP = REPO_ROOT / "docs" / "storage-table-owners.toml"
STORAGE_MODULE = REPO_ROOT / "crates" / "codegg-core" / "src" / "storage" / "mod.rs"

GENERATED_HEADER = (
    "<!-- AUTO-GENERATED by "
    "crates/codegg-core/src/session/schema/storage_catalog.rs — DO NOT EDIT -->"
)
UPDATE_COMMAND = (
    "CODEGG_UPDATE_STORAGE_CATALOG=1 cargo test -p codegg-core storage_catalog"
)

TABLE_HEADING = re.compile(r"^### `([^`]+)`$")
BACKTICK_FIRST_CELL = re.compile(r"^\| `([^`]+)`")
LAYOUT_LINE = re.compile(r"^- Layout version: \*\*(\d+)\*\*$", re.MULTILINE)
LAYOUT_CONSTANT = re.compile(r"STORAGE_LAYOUT_VERSION\s*:\s*u32\s*=\s*(\d+)")


def parse_layout_version(source: str) -> int:
    match = LAYOUT_CONSTANT.search(source)
    if not match:
        raise ValueError("STORAGE_LAYOUT_VERSION not found")
    return int(match.group(1))


def parse_tables(text: str) -> list[dict[str, object]]:
    """Parse the catalog's per-table sections.

    A table section is `### `<name>``, then `- Owner:`, `- Introduced:`, a
    `- Columns:` table and a `- Indexes:` table. The section label is tracked so
    an index row is never counted as a column.
    """
    tables: list[dict[str, object]] = []
    current: dict[str, object] | None = None
    section: str | None = None
    for line in text.splitlines():
        heading = TABLE_HEADING.match(line)
        if heading:
            current = {
                "name": heading.group(1),
                "owner": None,
                "introduced": None,
                "columns": [],
                "indexes": [],
            }
            tables.append(current)
            section = None
            continue
        if current is None:
            continue
        if line.startswith("## "):
            current = None
            continue
        if line.startswith("- Owner: "):
            current["owner"] = line[len("- Owner: ") :].strip().strip("`")
            continue
        if line.startswith("- Introduced: "):
            current["introduced"] = line[len("- Introduced: ") :].strip()
            continue
        if line == "- Columns:":
            section = "columns"
            continue
        if line.startswith("- Indexes:"):
            section = "indexes"
            continue
        cell = BACKTICK_FIRST_CELL.match(line)
        if cell and section in ("columns", "indexes"):
            current[section].append(cell.group(1))  # type: ignore[union-attr]
    return tables


def validate(
    catalog_text: str,
    owners: dict[str, str],
    layout_version: int,
    owner_exists,
) -> list[str]:
    """Return one failure string per violated property; empty means valid."""
    failures: list[str] = []
    lines = catalog_text.splitlines()
    if not lines or lines[0] != GENERATED_HEADER:
        failures.append(
            "the generated header is missing or hand-edited; expected "
            f"exactly {GENERATED_HEADER!r}"
        )
    if len(lines) < 2 or UPDATE_COMMAND not in lines[1]:
        failures.append(
            f"the update command {UPDATE_COMMAND!r} is missing from the "
            "catalog's second line"
        )

    declared = LAYOUT_LINE.search(catalog_text)
    if not declared:
        failures.append("the catalog declares no `- Layout version: **N**` line")
    elif int(declared.group(1)) != layout_version:
        failures.append(
            f"the catalog declares layout version {declared.group(1)}, but "
            f"STORAGE_LAYOUT_VERSION is {layout_version}"
        )

    tables = parse_tables(catalog_text)
    if not tables:
        failures.append("the catalog contains no table sections")
    seen: dict[str, dict[str, object]] = {}
    for table in tables:
        name = table["name"]
        if name in seen:
            failures.append(f"table `{name}` is declared more than once")
            continue
        seen[name] = table
        if not table["owner"]:
            failures.append(f"table `{name}` has no owner")
        if not table["introduced"]:
            failures.append(f"table `{name}` has no introducing migration")
        columns = table["columns"]
        duplicates = sorted(
            {name for name in columns if columns.count(name) > 1}  # type: ignore[union-attr]
        )
        if duplicates:
            failures.append(
                f"table `{name}` declares column(s) {duplicates} more than once"
            )

    for name, owner in sorted(owners.items()):
        if name not in seen:
            failures.append(
                f"the owner map names `{name}`, which the catalog does not contain"
            )
            continue
        declared_owner = seen[name]["owner"]
        if declared_owner != owner:
            failures.append(
                f"table `{name}` declares owner `{declared_owner}` but the owner "
                f"map declares `{owner}`"
            )
    for owner in sorted(set(owners.values())):
        if not owner_exists(owner):
            failures.append(f"owner module `{owner}` does not exist")

    return failures


def _self_test() -> int:
    """Inject each defect class and prove the guard rejects it."""
    header = f"{GENERATED_HEADER}\n<!-- Regenerate: {UPDATE_COMMAND} -->\n\n"
    base = (
        header
        + "# Storage Catalog\n\n"
        + "- Layout version: **95**\n\n"
        + "## Tables\n\n"
        + "### `widget`\n\n"
        + "- Owner: `crates/codegg-core/src/widget.rs`\n"
        + "- Introduced: v7\n"
        + "- Columns:\n\n"
        + "| Column | Type | Nullable | Primary key | Notes |\n"
        + "| --- | --- | --- | --- | --- |\n"
        + "| `id` | TEXT | NOT NULL | 1 | - |\n"
        + "| `label` | TEXT | NULL | 0 | - |\n\n"
        + "- Indexes: none\n"
    )
    valid_owners = {"widget": "crates/codegg-core/src/widget.rs"}
    cases = [
        ("control: a valid catalog passes", base, valid_owners, True, None),
        (
            "a table with no owner is rejected",
            base.replace("- Owner: `crates/codegg-core/src/widget.rs`\n", ""),
            valid_owners,
            False,
            "has no owner",
        ),
        (
            "an owner entry naming a missing table is rejected",
            base,
            {**valid_owners, "ghost": "crates/codegg-core/src/ghost.rs"},
            False,
            "the owner map names `ghost`",
        ),
        (
            "a duplicated column is rejected",
            base.replace(
                "| `label` | TEXT | NULL | 0 | - |\n",
                "| `label` | TEXT | NULL | 0 | - |\n"
                "| `label` | TEXT | NULL | 0 | - |\n",
            ),
            valid_owners,
            False,
            "declares column(s) ['label'] more than once",
        ),
        (
            "a mismatched layout version is rejected",
            base.replace("**95**", "**94**"),
            valid_owners,
            False,
            "STORAGE_LAYOUT_VERSION is 95",
        ),
        (
            "a hand-edited header is rejected",
            base.replace(
                GENERATED_HEADER,
                "<!-- hand written, do not regenerate -->",
                1,
            ),
            valid_owners,
            False,
            "generated header is missing",
        ),
        (
            "a catalog owner that disagrees with the map is rejected",
            base.replace("crates/codegg-core/src/widget.rs", "crates/codegg-core/src/other.rs"),
            valid_owners,
            False,
            "but the owner map declares",
        ),
    ]
    failures = 0
    for description, text, owners, should_pass, needle in cases:
        problems = validate(text, owners, 95, lambda _: True)
        passed = not problems if should_pass else any(needle in p for p in problems)
        print(f"  [{'PASS' if passed else 'FAIL'}] self-test: {description}")
        if not passed:
            failures += 1
            print(f"      problems: {problems}")
    if failures:
        print(f"{failures} self-test case(s) FAILED.")
        return 1
    print(f"All {len(cases)} guard self-test cases passed.")
    return 0


def main() -> int:
    if "--self-test" in sys.argv:
        return _self_test()

    if not CATALOG.is_file():
        print(f"  FAIL: {CATALOG.relative_to(REPO_ROOT)} does not exist")
        return 1
    if not OWNER_MAP.is_file():
        print(f"  FAIL: {OWNER_MAP.relative_to(REPO_ROOT)} does not exist")
        return 1

    layout_version = parse_layout_version(
        STORAGE_MODULE.read_text(encoding="utf-8")
    )
    owners = tomllib.loads(OWNER_MAP.read_text(encoding="utf-8")).get("owners", {})
    problems = validate(
        CATALOG.read_text(encoding="utf-8"),
        owners,
        layout_version,
        lambda path: (REPO_ROOT / path).is_file(),
    )

    catalog_text = CATALOG.read_text(encoding="utf-8")
    tables = parse_tables(catalog_text)
    print()
    print(
        f"  catalog: {len(tables)} tables, "
        f"{sum(len(t['indexes']) for t in tables)} indexes, "  # type: ignore[arg-type]
        f"layout version {layout_version}"
    )
    for problem in problems:
        print(f"  [FAIL] {problem}")
    if problems:
        print(f"\n{len(problems)} storage-catalog violation(s).")
        return 1
    print("  [PASS] the generated storage catalog is structurally sound.")
    print(f"{len(tables)}/{len(tables)} checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
