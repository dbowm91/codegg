#!/usr/bin/env python3
"""Structural guard for the generated tool-surface catalog (M004).

`architecture/tool-catalog.md` is produced by constructing the real registry in
`tests/tool_catalog/render.inc`; its freshness is the `tool_catalog` test
family's job, which runs in the nextest sweep. This guard is the cheap half that
runs in `verify.sh quick` and CI, where no test runs. It checks the properties a
stale or hand-edited file breaks and a regeneration does not:

  * the generated header and its update command,
  * every row is well formed: five cells, a known safety class, a known effect
    class, a boolean defer flag, and `visible` or `hidden (<reason>)`,
  * no tool name appears twice within one section,
  * the sections are exactly the declared matrix, in the declared order,
  * every tool name the hand-written prose still mentions appears in the
    catalog.

It deliberately does **not** re-derive the registry. Reading Rust to guess what
`ToolRegistry::with_options` registers is how a guard starts disagreeing with
the thing it is supposed to check; the comparison test in
`tests/tool_catalog/comparison.inc` owns that, and the two layers are separate on
purpose.

`--self-test` injects each defect class into a synthetic catalog and proves the
guard rejects it: a duplicate row, a malformed row, a missing section, a prose
name the catalog does not contain, and a hand-edited header without the
generated marker.

Exit code 0 if all checks pass, 1 if any fail.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CATALOG = REPO_ROOT / "architecture" / "tool-catalog.md"
SURFACE_DOC = REPO_ROOT / "architecture" / "agent-tool-surface.md"

# The exact first line the generator writes. Kept here as a literal *and*
# compared against the generator's own `GENERATED_HEADER`, so the two cannot
# drift.
GENERATED_HEADER = (
    "<!-- AUTO-GENERATED by tests/tool_catalog/render.inc — DO NOT EDIT -->"
)
UPDATE_COMMAND = "CODEGG_UPDATE_TOOL_CATALOG=1 cargo test --test tool_catalog"

# The declared matrix, in section order. A new surface is a deliberate edit here
# as well as in the renderer's `SURFACES`: a guard that read the section list out
# of the artifact it is checking would accept any file.
SURFACES = ["default", "plan-mode", "restricted-subagent", "backend-disabled"]

CATEGORIES = {"ReadOnly", "SafeMutating", "Mutating", "ShellExec"}
EFFECT_CLASSES = {
    "read_only",
    "read_validate",
    "safe_repeat",
    "idempotent_mutating",
    "non_idempotent",
    "process_exec",
}

SECTION_BLOCK = "## Tool surfaces"
SECTION_HEADING = re.compile(r"^### (\S+)$")
ROW = re.compile(r"^\| `([^`]+)` \|", re.UNICODE)
BACKTICK = re.compile(r"`([^`]+)`")
BARE_TOOL_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
FENCE = re.compile(r"^```[^`]*$", re.MULTILINE)
ROW_CELLS = 5


def prose_tokens(text: str) -> list[str]:
    """Return the bare, backticked identifiers the prose still names.

    Fenced code blocks are removed first. A fence line is itself three
    backticks, so pairing spans across one desynchronises every following inline
    span — the extraction would then report an arbitrary subset and the check
    would pass on a document it never read. A bare lowercase identifier in
    backticks is the document's convention for a tool name; anything with a
    path, a parenthesis, an operator or a capital is Rust vocabulary and is
    ignored.
    """
    body = "\n".join(
        line for line in text.splitlines() if not FENCE.match(line)
    )
    return sorted({token for token in BACKTICK.findall(body) if BARE_TOOL_NAME.match(token)})


def parse_sections(text: str) -> list[tuple[str, list[str]]]:
    """Return `(section name, raw row lines)` in file order.

    Only the `## Tool surfaces` block is scanned: the document's own explanation
    has headings of its own, and counting those as surfaces would make a missing
    section invisible behind them.
    """
    sections: list[tuple[str, list[str]]] = []
    in_block = False
    current: list[str] | None = None
    for line in text.splitlines():
        if line.startswith("## "):
            in_block = line.strip() == SECTION_BLOCK
            current = None
            continue
        if not in_block:
            continue
        heading = SECTION_HEADING.match(line)
        if heading:
            current = []
            sections.append((heading.group(1), current))
            continue
        if line.startswith("| `") and current is not None:
            current.append(line)
    return sections


def parse_row(line: str) -> tuple[str, list[str]] | None:
    """Split one row line into its name and cells, or `None` when malformed."""
    cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
    if len(cells) != ROW_CELLS:
        return None
    name = cells[0]
    if not (name.startswith("`") and name.endswith("`")) or len(name) < 3:
        return None
    return name.strip("`"), cells


def validate(catalog_text: str, prose_text: str) -> list[str]:
    """Return one failure string per violated property; empty means valid."""
    failures: list[str] = []
    lines = catalog_text.splitlines()
    if not lines or lines[0] != GENERATED_HEADER:
        failures.append(
            "the generated header is missing or hand-edited; expected exactly "
            f"{GENERATED_HEADER!r}"
        )
    if len(lines) < 2 or UPDATE_COMMAND not in lines[1]:
        failures.append(
            f"the update command {UPDATE_COMMAND!r} is missing from the catalog's "
            "second line"
        )

    sections = parse_sections(catalog_text)
    names: set[str] = set()
    if not sections:
        failures.append(f"the catalog contains no `{SECTION_BLOCK}` sections")
    section_names = [name for name, _ in sections]
    missing = [name for name in SURFACES if name not in section_names]
    if missing:
        failures.append(f"the catalog is missing declared section(s) {missing}")
    undeclared = [name for name in section_names if name not in SURFACES]
    if undeclared:
        failures.append(f"the catalog declares undeclared section(s) {undeclared}")
    declared_order = [name for name in SURFACES if name in section_names]
    if section_names != declared_order:
        failures.append(
            f"sections are not in the declared order: {section_names} (declared "
            f"{declared_order})"
        )

    for section, row_lines in sections:
        seen: set[str] = set()
        for line in row_lines:
            parsed = parse_row(line)
            if parsed is None:
                failures.append(f"section `{section}` has a malformed row: {line!r}")
                continue
            name, cells = parsed
            if name in seen:
                failures.append(f"section `{section}` lists `{name}` more than once")
            seen.add(name)
            names.add(name)
            category, effect, defer, visibility = cells[1:5]
            if category not in CATEGORIES:
                failures.append(
                    f"section `{section}` row `{name}` has category {category!r}, which "
                    f"is not one of {sorted(CATEGORIES)}"
                )
            if effect not in EFFECT_CLASSES:
                failures.append(
                    f"section `{section}` row `{name}` has effect class {effect!r}, which "
                    f"is not one of {sorted(EFFECT_CLASSES)}"
                )
            if defer not in {"yes", "no"}:
                failures.append(
                    f"section `{section}` row `{name}` has defer flag {defer!r}, not yes/no"
                )
            if visibility != "visible" and not (
                visibility.startswith("hidden (")
                and visibility.endswith(")")
                and len(visibility) > len("hidden ()")
            ):
                failures.append(
                    f"section `{section}` row `{name}` has visibility {visibility!r}; a "
                    "hidden row must state its reason"
                )

    referenced = prose_tokens(prose_text)
    absent = [token for token in referenced if token not in names]
    if absent:
        failures.append(
            f"{SURFACE_DOC.name} still names {absent}, which the catalog does not list"
        )

    return failures


def _self_test() -> int:
    """Inject each defect class and prove the guard rejects it."""
    header = f"{GENERATED_HEADER}\n<!-- Regenerate: {UPDATE_COMMAND} -->\n\n"
    row = "| `{name}` | ReadOnly | read_only | no | visible |\n"

    def section(name: str, rows: list[str]) -> str:
        return f"### {name}\n\nA surface.\n\n| Tool | Category | Effect class | Defer | Visibility |\n| --- | --- | --- | --- | --- |\n" + "".join(
            row.format(name=item) for item in rows
        ) + "\n"

    base = (
        header
        + "# Tool Catalog\n\n"
        + f"{SECTION_BLOCK}\n\n"
        + section("default", ["read", "write"])
        + section("plan-mode", ["read"])
        + section("restricted-subagent", ["read"])
        + section("backend-disabled", ["security"])
        + "## Non-claims\n\nNothing.\n"
    )
    prose = "The `read` tool, the `write` tool, and the `security` tool.\n"

    cases = [
        ("control: a valid catalog passes", base, prose, None),
        (
            "a duplicate row in one section is rejected",
            base.replace(
                section("default", ["read", "write"]),
                section("default", ["read", "read"]),
            ),
            prose,
            "lists `read` more than once",
        ),
        (
            "a malformed row is rejected",
            base.replace(
                "| `write` | ReadOnly | read_only | no | visible |\n",
                "| `write` | ReadOnly | not_an_effect | no | visible |\n",
            ),
            prose,
            "has effect class 'not_an_effect'",
        ),
        (
            "a missing section is rejected",
            base.replace(section("restricted-subagent", ["read"]), ""),
            prose,
            "missing declared section(s) ['restricted-subagent']",
        ),
        (
            "a prose name the catalog omits is rejected",
            base,
            prose + "It also mentions `git_query`.\n",
            "still names ['git_query']",
        ),
        (
            "a hand-edited header is rejected",
            base.replace(
                GENERATED_HEADER, "<!-- hand written, do not regenerate -->", 1
            ),
            prose,
            "generated header is missing",
        ),
        (
            "an empty hidden reason is rejected",
            base.replace(
                "| `security` | ReadOnly | read_only | no | visible |\n",
                "| `security` | ReadOnly | read_only | no | hidden () |\n",
            ),
            prose,
            "must state its reason",
        ),
    ]
    failures = 0
    for description, text, doc, needle in cases:
        problems = validate(text, doc)
        if needle is None:
            passed = not problems
        else:
            passed = any(needle in problem for problem in problems)
        print(f"  [{'PASS' if passed else 'FAIL'}] self-test: {description}")
        if not passed:
            failures += 1
            print(f"      problems: {problems}")
    if failures:
        print(f"{failures} self-test case(s) FAILED.")
        return 1
    print(f"All {len(cases)} guard self-test cases passed.")
    return 0


def main() -> int:
    if "--self-test" in sys.argv:
        return _self_test()
    if not CATALOG.exists():
        print(f"FAIL: the catalog is missing at {CATALOG}")
        return 1
    if not SURFACE_DOC.exists():
        print(f"FAIL: the hand-written surface document is missing at {SURFACE_DOC}")
        return 1
    failures = validate(
        CATALOG.read_text(encoding="utf-8"),
        SURFACE_DOC.read_text(encoding="utf-8"),
    )
    if failures:
        print(f"FAIL: {CATALOG.relative_to(REPO_ROOT)} is not the catalog it claims to be:")
        for failure in failures:
            print(f"  - {failure}")
        print(f"Regenerate with `{UPDATE_COMMAND}`.")
        return 1
    print(
        f"OK: {CATALOG.relative_to(REPO_ROOT)} parses, declares its {len(SURFACES)} "
        "sections in order, and covers every tool the prose names."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
