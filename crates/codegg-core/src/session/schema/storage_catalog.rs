//! The generated storage catalog (M006).
//!
//! Running the real chain one step at a time against a private temporary
//! database is the only way to attribute a table to the migration that created
//! it; a parser over `schema.rs` would be a second implementation of the
//! migrations. A table with no entry in `docs/storage-table-owners.toml` fails
//! generation, and `scripts/check_storage_catalog.py` fails on a stale entry.
//!
//! Regenerate with
//! `CODEGG_UPDATE_STORAGE_CATALOG=1 cargo test -p codegg-core storage_catalog`.
//! Test-only: this child module of `session::schema` can call the private
//! dispatcher, so production needs no partial-migration API.

use std::collections::BTreeMap;
use std::path::{Path as FsPath, PathBuf};

use sqlx::sqlite::{SqliteConnectOptions, SqlitePoolOptions};
use sqlx::{Row, SqlitePool};

use crate::storage::STORAGE_LAYOUT_VERSION;

/// The first line of the catalog; the structural guard requires it verbatim.
pub(crate) const GENERATED_HEADER: &str = "<!-- AUTO-GENERATED by crates/codegg-core/src/session/schema/storage_catalog.rs — DO NOT EDIT -->";

/// The command that regenerates the catalog, quoted on its second line.
pub(crate) const UPDATE_COMMAND: &str =
    "CODEGG_UPDATE_STORAGE_CATALOG=1 cargo test -p codegg-core storage_catalog";

const BOOTSTRAP_DDL: &str = "CREATE TABLE IF NOT EXISTS migration_version (\n    id INTEGER PRIMARY KEY CHECK (id = 1),\n    version INTEGER NOT NULL DEFAULT 0\n)";

/// One column as `pragma table_info` reports it.
#[derive(Clone, Debug, PartialEq, Eq)]
struct Column {
    column_type: String,
    not_null: bool,
    primary_key_position: i64,
}

/// The structural surface after one migration step.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
struct Snapshot {
    tables: BTreeMap<String, BTreeMap<String, Column>>,
    indexes: BTreeMap<String, String>,
}

/// Where one table, column, or index first appeared.
#[derive(Debug)]
struct Attribution {
    /// `0` is the bootstrap table `migrate()` creates before v1.
    introduced: u32,
    columns: BTreeMap<String, (u32, Option<u32>)>,
    indexes: BTreeMap<String, u32>,
}

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(FsPath::parent)
        .expect("the crate directory has a parent")
        .to_path_buf()
}

fn catalog_path() -> PathBuf {
    repo_root().join("architecture").join("storage-catalog.md")
}

fn owner_map_path() -> PathBuf {
    repo_root().join("docs").join("storage-table-owners.toml")
}

fn load_owner_map() -> BTreeMap<String, String> {
    let path = owner_map_path();
    let text = std::fs::read_to_string(&path).unwrap_or_else(|error| {
        panic!("cannot read {} ({error})", path.display());
    });
    let parsed: toml::Table = toml::from_str(&text)
        .unwrap_or_else(|error| panic!("{} is not valid TOML ({error})", path.display()));
    parsed
        .get("owners")
        .and_then(toml::Value::as_table)
        .unwrap_or_else(|| panic!("{} has no [owners] table", path.display()))
        .iter()
        .map(|(table, owner)| {
            let owner = owner
                .as_str()
                .unwrap_or_else(|| panic!("owner of `{table}` is not a string"));
            (table.clone(), owner.to_string())
        })
        .collect()
}

async fn open_private_pool(dir: &FsPath) -> Result<SqlitePool, String> {
    let db = dir.join("storage-catalog.sqlite");
    SqlitePoolOptions::new()
        .max_connections(1)
        .connect_with(
            SqliteConnectOptions::new()
                .filename(&db)
                .create_if_missing(true),
        )
        .await
        .map_err(|error| format!("open {}: {error}", db.display()))
}

async fn column_snapshot(
    pool: &SqlitePool,
    table: &str,
) -> Result<BTreeMap<String, Column>, String> {
    let rows = sqlx::query(&format!("PRAGMA table_info(\"{table}\")"))
        .fetch_all(pool)
        .await
        .map_err(|error| format!("read columns of `{table}`: {error}"))?;
    let mut columns = BTreeMap::new();
    for row in rows {
        let name: String = row
            .try_get("name")
            .map_err(|error| format!("column name of `{table}`: {error}"))?;
        let column = Column {
            column_type: row.try_get("type").unwrap_or_default(),
            not_null: row.try_get::<i64, _>("notnull").unwrap_or_default() != 0,
            primary_key_position: row.try_get("pk").unwrap_or_default(),
        };
        columns.insert(name, column);
    }
    Ok(columns)
}

async fn snapshot(pool: &SqlitePool) -> Result<Snapshot, String> {
    let mut snapshot = Snapshot::default();
    let tables = sqlx::query(
        "SELECT name FROM sqlite_master \
         WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
    )
    .fetch_all(pool)
    .await
    .map_err(|error| format!("list tables: {error}"))?;
    for row in tables {
        let table: String = row
            .try_get("name")
            .map_err(|error| format!("table name: {error}"))?;
        let columns = column_snapshot(pool, &table).await?;
        snapshot.tables.insert(table, columns);
    }
    let indexes = sqlx::query(
        "SELECT name, tbl_name FROM sqlite_master \
         WHERE type = 'index' AND sql IS NOT NULL ORDER BY name",
    )
    .fetch_all(pool)
    .await
    .map_err(|error| format!("list indexes: {error}"))?;
    for row in indexes {
        let name: String = row
            .try_get("name")
            .map_err(|error| format!("index name: {error}"))?;
        let table: String = row
            .try_get("tbl_name")
            .map_err(|error| format!("index table: {error}"))?;
        snapshot.indexes.insert(name, table);
    }
    Ok(snapshot)
}

/// The schema after every step of the chain, `0` being the bootstrap marker.
async fn snapshots() -> Result<Vec<(u32, Snapshot)>, String> {
    let dir = tempfile::tempdir().map_err(|error| format!("create temp dir: {error}"))?;
    snapshots_in(dir.path()).await
}

async fn snapshots_in(dir: &FsPath) -> Result<Vec<(u32, Snapshot)>, String> {
    let pool = open_private_pool(dir).await?;
    let result = async {
        sqlx::query(BOOTSTRAP_DDL)
            .execute(&pool)
            .await
            .map_err(|error| format!("create migration marker: {error}"))?;
        let mut snapshots = vec![(0, snapshot(&pool).await?)];
        for version in 1..=STORAGE_LAYOUT_VERSION {
            super::migrate_and_record(&pool, i64::from(version))
                .await
                .map_err(|error| format!("migration v{version}: {error}"))?;
            snapshots.push((version, snapshot(&pool).await?));
        }
        Ok(snapshots)
    }
    .await;
    pool.close().await;
    result
}

fn attribute(snapshots: &[(u32, Snapshot)]) -> BTreeMap<String, Attribution> {
    let final_snapshot = &snapshots.last().expect("the chain produced no snapshots").1;
    let mut attributed = BTreeMap::new();
    for (table, final_columns) in &final_snapshot.tables {
        let introduced = snapshots
            .iter()
            .find(|(_, snapshot)| snapshot.tables.contains_key(table))
            .map(|(version, _)| *version)
            .expect("a final table appeared in some snapshot");
        let mut columns = BTreeMap::new();
        for name in final_columns.keys() {
            let introduced_value = snapshots
                .iter()
                .find_map(|(version, snapshot)| {
                    snapshot
                        .tables
                        .get(table)
                        .and_then(|columns| columns.get(name))
                        .map(|column| (*version, column))
                })
                .expect("a final column appeared in some snapshot");
            let altered = snapshots
                .iter()
                .filter(|(version, _)| *version > introduced_value.0)
                .find(|(_, snapshot)| {
                    snapshot
                        .tables
                        .get(table)
                        .and_then(|columns| columns.get(name))
                        .is_some_and(|column| column != introduced_value.1)
                })
                .map(|(version, _)| *version);
            columns.insert(name.clone(), (introduced_value.0, altered));
        }
        let mut indexes = BTreeMap::new();
        for (index, owner) in &final_snapshot.indexes {
            if owner != table {
                continue;
            }
            let introduced = snapshots
                .iter()
                .find(|(_, snapshot)| snapshot.indexes.get(index) == Some(table))
                .map(|(version, _)| *version)
                .expect("a final index appeared in some snapshot");
            indexes.insert(index.clone(), introduced);
        }
        attributed.insert(
            table.clone(),
            Attribution {
                introduced,
                columns,
                indexes,
            },
        );
    }
    attributed
}

fn plural(count: usize, noun: &str) -> String {
    if count == 1 {
        format!("1 {noun}")
    } else if noun.ends_with('x') {
        format!("{count} {noun}es")
    } else {
        format!("{count} {noun}s")
    }
}

fn describe_effect(previous: &Snapshot, current: &Snapshot) -> String {
    let new_tables = current
        .tables
        .keys()
        .filter(|table| !previous.tables.contains_key(*table))
        .count();
    let dropped_tables = previous
        .tables
        .keys()
        .filter(|table| !current.tables.contains_key(*table))
        .count();
    let new_indexes = current
        .indexes
        .keys()
        .filter(|index| !previous.indexes.contains_key(*index))
        .count();
    let dropped_indexes = previous
        .indexes
        .keys()
        .filter(|index| !current.indexes.contains_key(*index))
        .count();
    let altered_columns: usize = current
        .tables
        .iter()
        .map(|(table, columns)| {
            columns
                .iter()
                .filter(|(name, column)| {
                    previous
                        .tables
                        .get(table)
                        .and_then(|before| before.get(*name))
                        .is_some_and(|before| before != *column)
                })
                .count()
        })
        .sum();
    let mut parts = Vec::new();
    if new_tables > 0 {
        parts.push(plural(new_tables, "table"));
    }
    if new_indexes > 0 {
        parts.push(plural(new_indexes, "index"));
    }
    if altered_columns > 0 {
        parts.push(format!("{altered_columns} altered column(s)"));
    }
    if dropped_tables > 0 {
        parts.push(plural(dropped_tables, "dropped table"));
    }
    if dropped_indexes > 0 {
        parts.push(plural(dropped_indexes, "dropped index"));
    }
    if parts.is_empty() {
        "none".to_string()
    } else {
        parts.join(", ")
    }
}

fn introduced_label(version: u32) -> String {
    if version == 0 {
        "bootstrap (before v1)".to_string()
    } else {
        format!("v{version}")
    }
}

fn render_catalog(
    snapshots: &[(u32, Snapshot)],
    owners: &BTreeMap<String, String>,
) -> Result<String, Vec<String>> {
    let final_snapshot = &snapshots.last().expect("the chain produced no snapshots").1;
    let attributed = attribute(snapshots);
    let mut problems = Vec::new();
    for table in final_snapshot.tables.keys() {
        if !owners.contains_key(table) {
            problems.push(format!(
                "table `{table}` has no owner entry; add \
                 `{table} = \"<module>\"` to docs/storage-table-owners.toml"
            ));
        }
    }
    for table in owners.keys() {
        if !final_snapshot.tables.contains_key(table) {
            problems.push(format!(
                "docs/storage-table-owners.toml names `{table}`, which the \
                 migration chain does not create"
            ));
        }
    }
    if !problems.is_empty() {
        return Err(problems);
    }

    let table_count = final_snapshot.tables.len();
    let index_count = final_snapshot.indexes.len();
    let mut out = String::new();
    out.push_str(GENERATED_HEADER);
    out.push('\n');
    out.push_str(&format!("<!-- Regenerate: {UPDATE_COMMAND} -->\n\n"));
    out.push_str("# Storage Catalog\n\n");
    out.push_str(
        "This file is produced by running the real migration chain in\n\
         `crates/codegg-core/src/session/schema.rs` one step at a time against a\n\
         private temporary database and reading the schema after each step. It\n\
         describes structure only: no row data, no sample values, and no\n\
         behaviour. Do not edit it by hand.\n\n",
    );
    out.push_str(
        "Each table names the module that owns it in\n\
         `docs/storage-table-owners.toml` — the one hand-maintained input. A table\n\
         with no entry there fails generation and `scripts/check_storage_catalog.py`.\n\n",
    );
    out.push_str(&format!(
        "- Layout version: **{STORAGE_LAYOUT_VERSION}**\n\
         - Migrations: **{STORAGE_LAYOUT_VERSION}**\n\
         - Tables: **{table_count}**\n\
         - Indexes: **{index_count}**\n\n"
    ));
    out.push_str("## Migrations\n\n");
    out.push_str("| Migration | Structural effect |\n| --- | --- |\n");
    let mut previous = snapshots
        .first()
        .expect("the chain produced no snapshots")
        .1
        .clone();
    for (version, current) in snapshots {
        if *version == 0 {
            continue;
        }
        out.push_str(&format!(
            "| v{version} | {} |\n",
            describe_effect(&previous, current)
        ));
        previous = current.clone();
    }
    out.push_str("\n## Tables\n\n");
    for (table, columns) in &final_snapshot.tables {
        let attribution = &attributed[table];
        out.push_str(&format!("### `{table}`\n\n"));
        out.push_str(&format!("- Owner: `{}`\n", owners[table]));
        out.push_str(&format!(
            "- Introduced: {}\n",
            introduced_label(attribution.introduced)
        ));
        out.push_str("- Columns:\n\n");
        out.push_str("| Column | Type | Nullable | Primary key | Notes |\n");
        out.push_str("| --- | --- | --- | --- | --- |\n");
        for (name, column) in columns {
            let (_, altered) = attribution.columns[name];
            let notes = altered.map_or_else(|| "-".to_string(), |v| format!("altered in v{v}"));
            let column_type = if column.column_type.is_empty() {
                "-"
            } else {
                column.column_type.as_str()
            };
            out.push_str(&format!(
                "| `{name}` | {column_type} | {} | {} | {notes} |\n",
                if column.not_null { "NOT NULL" } else { "NULL" },
                column.primary_key_position
            ));
        }
        if attribution.indexes.is_empty() {
            out.push_str("\n- Indexes: none\n\n");
        } else {
            out.push_str("\n- Indexes:\n\n");
            out.push_str("| Index | Introduced |\n| --- | --- |\n");
            for (index, version) in &attribution.indexes {
                out.push_str(&format!("| `{index}` | v{version} |\n"));
            }
            out.push('\n');
        }
    }
    Ok(out)
}

async fn generate() -> Result<String, String> {
    let snapshots = snapshots().await?;
    let owners = load_owner_map();
    render_catalog(&snapshots, &owners).map_err(|problems| problems.join("\n"))
}

fn validate_update_mode() {
    let update = std::env::var("CODEGG_UPDATE_STORAGE_CATALOG").as_deref() == Ok("1");
    assert!(
        !(update && std::env::var_os("CI").is_some()),
        "CODEGG_UPDATE_STORAGE_CATALOG is set in CI; the committed catalog is \
         the input there, never a build product"
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    fn synthetic_snapshot(columns: &[(&str, &str, bool)]) -> Snapshot {
        let mut snapshot = Snapshot::default();
        let mut table = BTreeMap::new();
        for (name, column_type, not_null) in columns {
            table.insert(
                (*name).to_string(),
                Column {
                    column_type: (*column_type).to_string(),
                    not_null: *not_null,
                    primary_key_position: 0,
                },
            );
        }
        snapshot.tables.insert("widget".to_string(), table);
        snapshot
    }

    fn synthetic_owners() -> BTreeMap<String, String> {
        BTreeMap::from([(
            "widget".to_string(),
            "crates/codegg-core/src/session/schema.rs".to_string(),
        )])
    }

    #[tokio::test]
    async fn catalog_matches_the_committed_file() {
        validate_update_mode();
        let rendered = generate().await.unwrap_or_else(|error| panic!("{error}"));
        let path = catalog_path();
        if std::env::var("CODEGG_UPDATE_STORAGE_CATALOG").as_deref() == Ok("1") {
            std::fs::write(&path, &rendered).expect("the catalog is writable");
        }
        let committed = std::fs::read_to_string(&path).unwrap_or_else(|error| {
            panic!(
                "cannot read {} ({error}); regenerate with `{UPDATE_COMMAND}`",
                path.display()
            )
        });
        assert_eq!(
            committed,
            rendered,
            "{} is stale; regenerate with `{UPDATE_COMMAND}`",
            path.display()
        );
        let regenerated = generate().await.unwrap_or_else(|error| panic!("{error}"));
        assert_eq!(
            rendered, regenerated,
            "the catalog must regenerate byte-identically"
        );
    }

    #[tokio::test]
    async fn a_known_table_is_attributed_to_the_migration_that_created_it() {
        let snapshots = snapshots().await.expect("the migration chain runs");
        let attributed = attribute(&snapshots);
        assert_eq!(
            attributed.len(),
            snapshots
                .last()
                .expect("the chain produced a snapshot")
                .1
                .tables
                .len(),
            "every final table has exactly one attribution"
        );
        assert_eq!(
            attributed["turn_request_ledger"].introduced, 95,
            "the ledger table is created by migrate_v95"
        );
        assert_eq!(
            attributed["agent_run"].introduced, 37,
            "the run table is created by migrate_v37"
        );
        assert_eq!(
            attributed["migration_version"].introduced, 0,
            "the marker is bootstrapped before v1"
        );
    }

    #[test]
    fn an_altered_column_is_reported_as_altered_not_introduced_twice() {
        let snapshots = vec![
            (0, Snapshot::default()),
            (
                1,
                synthetic_snapshot(&[("id", "TEXT", true), ("label", "TEXT", false)]),
            ),
            (
                2,
                synthetic_snapshot(&[("id", "TEXT", true), ("label", "TEXT", false)]),
            ),
            (
                3,
                synthetic_snapshot(&[("id", "TEXT", true), ("label", "TEXT", true)]),
            ),
        ];
        let attributed = attribute(&snapshots);
        assert_eq!(attributed.len(), 1, "one table is attributed once");
        let (introduced, altered) = attributed["widget"].columns["label"];
        assert_eq!(introduced, 1, "the column is introduced once");
        assert_eq!(
            altered,
            Some(3),
            "a later nullability change is reported as an alter"
        );
    }

    #[test]
    fn an_unowned_table_fails_naming_the_table_and_the_entry_to_add() {
        let snapshots = vec![
            (0, Snapshot::default()),
            (1, synthetic_snapshot(&[("id", "TEXT", true)])),
        ];
        let problems = render_catalog(&snapshots, &BTreeMap::new())
            .expect_err("an unowned table must not render");
        assert!(
            problems
                .iter()
                .any(|problem| problem.contains("`widget`") && problem.contains("no owner entry")),
            "the failure names the table and the missing entry: {problems:?}"
        );
    }

    #[test]
    fn an_owner_entry_for_a_missing_table_is_rejected() {
        let snapshots = vec![
            (0, Snapshot::default()),
            (1, synthetic_snapshot(&[("id", "TEXT", true)])),
        ];
        let mut owners = synthetic_owners();
        owners.insert(
            "ghost".to_string(),
            "crates/codegg-core/src/session/schema.rs".to_string(),
        );
        let problems =
            render_catalog(&snapshots, &owners).expect_err("a stale owner entry must not render");
        assert!(
            problems.iter().any(|problem| problem.contains("`ghost`")),
            "the failure names the stale entry: {problems:?}"
        );
    }

    #[tokio::test]
    async fn the_generator_opens_only_a_private_removed_temporary_database() {
        let dir = tempfile::tempdir().expect("a temporary directory");
        let path = dir.path().to_path_buf();
        assert!(
            path.starts_with(std::env::temp_dir()),
            "the generator's database lives under the temporary directory"
        );
        assert!(
            !path.starts_with(crate::storage::DaemonPaths::default_data_root()),
            "the generator never opens a path under the user's data directory"
        );
        let snapshots = snapshots_in(&path)
            .await
            .expect("the chain runs in the pool");
        assert!(
            path.join("storage-catalog.sqlite").is_file(),
            "the observed schema came from the private database"
        );
        assert!(
            !snapshots.is_empty(),
            "the chain produced a snapshot per step"
        );
        drop(dir);
        assert!(
            !path.exists(),
            "the generator removes its database and directory"
        );
    }
}
