/// The one sentinel string value.
const SENTINEL: &str = "sentinel";

/// The section name a serialized key belongs to.
///
/// Configuration keys are serialized names, and `$`-prefixed keys are serde
/// renames of a schema field (`$schema` is `schema`). Provenance receives the
/// serialized spelling, so the mapping lives here rather than being duplicated
/// at every call site.
pub(crate) fn section_for_serialized_key(key: &str) -> &str {
    key.strip_prefix('$').unwrap_or(key)
}

/// The serialized top-level keys of the sentinel, mapped to their sections.
///
/// This is the catalog's key source. It is derived from the type through the
/// literal, so it cannot list a key the schema does not have.
pub(crate) fn catalog_keys() -> BTreeMap<String, String> {
    let value = serde_json::to_value(sentinel_config()).expect("the sentinel config serializes");
    let object = value.as_object().expect("Config serializes to an object");
    object
        .keys()
        .map(|key| (key.clone(), section_for_serialized_key(key).to_string()))
        .collect()
}

/// The catalog's file path.
pub(crate) fn catalog_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|path| path.parent())
        .expect("the crate directory has a parent")
        .join("architecture")
        .join("config-catalog.md")
}

/// Render the catalog.
///
/// Byte-for-byte deterministic: the key list is sorted, and every field comes
/// from the schema or the declared table.
pub(crate) fn render_catalog() -> String {
    let keys = catalog_keys();
    let defaults = serde_json::to_value(Config::default()).expect("the default config serializes");
    let defaults = defaults
        .as_object()
        .expect("Config serializes to an object");

    let mut out = String::new();
    out.push_str(GENERATED_HEADER);
    out.push('\n');
    out.push_str(&format!("<!-- Regenerate: {UPDATE_COMMAND} -->\n"));
    out.push('\n');
    out.push_str("# Configuration Catalog\n");
    out.push('\n');
    out.push_str("This file is generated from `Config` in `crates/codegg-config/src/schema.rs`.\n");
    out.push_str(
        "Its key list comes from a struct literal that names every `Config` field, so a\n",
    );
    out.push_str(
        "field added to the schema without a catalog row is a compile error, not a stale\n",
    );
    out.push_str("document. Do not edit this file by hand.\n");
    out.push('\n');
    out.push_str("## What the columns mean\n");
    out.push('\n');
    out.push_str("- **Key** — the key as a configuration file spells it.\n");
    out.push_str("- **Merge shape** — what `merge_configs` does with the section. `whole-value`\n");
    out.push_str("  replaces it, `field-by-field` combines its own fields, `union-of-keys`\n");
    out.push_str(
        "  combines a map's entries, `whole-value-with-inherit` replaces it except for a\n",
    );
    out.push_str("  declared inherited path, and `concatenate` appends.\n");
    out.push_str(
        "- **Attribution** — the rule `codegg-config`'s provenance engine enforces when it\n",
    );
    out.push_str("  names the layer that won a key. `last-containing` means the last layer that\n");
    out.push_str("  specifies the key (or the block containing it, when the merge replaces that\n");
    out.push_str("  block whole); `concatenate` means every containing layer contributes.\n");
    out.push_str("- **Combine depth** — how many leading path segments combine field by field.\n");
    out.push_str(
        "  `0` means the section itself replaces whole, so every key beneath it belongs to\n",
    );
    out.push_str("  the layer that specified the section; `1` means its own fields combine; `2`\n");
    out.push_str("  means a map's entries and their fields combine.\n");
    out.push_str(
        "- **Default** — `Config::default()`'s value for the key, or `—` when the default\n",
    );
    out.push_str(
        "  omits it. Every section is `—` today: every `Config` field is optional, so no\n",
    );
    out.push_str(
        "  section is populated by default. Field-level defaults live in the schema's own\n",
    );
    out.push_str("  `Default` implementations.\n");
    out.push_str("- **Note** — why a section's merge is not a plain last-wins replacement.\n");
    out.push('\n');
    out.push_str("## Non-claims\n");
    out.push('\n');
    out.push_str("- The catalog lists keys, merge shapes and attribution rules. It does not\n");
    out.push_str("  describe what a key does; `architecture/config.md` keeps that prose.\n");
    out.push_str("- It is not a validator. `Config::validate` is the validator.\n");
    out.push_str("- Rows are sections. A section's nested keys are covered by\n");
    out.push_str(
        "  `scripts/check_config_merge_coverage.py`, which descends into every reachable\n",
    );
    out.push_str("  nested config struct that owns its own `merge` method.\n");
    out.push('\n');
    out.push_str("## Sections\n");
    out.push('\n');
    out.push_str("| Key | Merge shape | Attribution | Combine depth | Default | Note |\n");
    out.push_str("|---|---|---|---|---|---|\n");

    for (key, section) in &keys {
        let declared = strategy_for(section);
        let (shape, rule, depth, note) = match declared {
            Some(entry) => (
                entry.shape.as_str(),
                entry.rule.as_str(),
                entry.combine_depth.to_string(),
                entry.note,
            ),
            None => ("undeclared", "undeclared", "—".to_string(), ""),
        };
        let default = defaults
            .get(key)
            .map(|value| {
                if value.is_null() {
                    "—".to_string()
                } else {
                    value.to_string()
                }
            })
            .unwrap_or_else(|| "—".to_string());
        out.push_str(&format!(
            "| `{key}` | {shape} | {rule} | {depth} | `{default}` | {note} |\n"
        ));
    }

    out.push('\n');
    out.push_str(&format!(
        "{} sections, {} of them declared with an exception note.\n",
        keys.len(),
        keys.values()
            .filter(|section| strategy_for(section).is_some_and(|e| !e.note.is_empty()))
            .count()
    ));
    out
}

/// The set of sections the catalog declares.
pub(crate) fn catalog_sections() -> BTreeSet<String> {
    catalog_keys().into_values().collect()
}

/// The shapes that must carry a note, for the tests that check the table.
pub(crate) fn is_plain(shape: MergeShape) -> bool {
    matches!(
        shape,
        MergeShape::WholeValue | MergeShape::FieldByField | MergeShape::UnionOfKeys
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::provenance::STRATEGY_TABLE;

    #[test]
    fn catalog_matches_the_committed_file() {
        let rendered = render_catalog();
        let path = catalog_path();
        if std::env::var("CODEGG_UPDATE_CONFIG_CATALOG").as_deref() == Ok("1") {
            std::fs::write(&path, &rendered).expect("the catalog is writable");
        }
        let committed = std::fs::read_to_string(&path).unwrap_or_else(|error| {
            panic!(
                "cannot read {} ({error}); regenerate with `{UPDATE_COMMAND}`",
                path.display()
            )
        });
        assert_eq!(
            committed,
            rendered,
            "{} is stale; regenerate with `{UPDATE_COMMAND}`",
            path.display()
        );
        assert_eq!(
            rendered,
            render_catalog(),
            "the catalog must regenerate byte-identically"
        );
    }

    #[test]
    fn every_config_section_has_exactly_one_strategy_entry() {
        let sections = catalog_sections();
        let declared: BTreeSet<&str> = STRATEGY_TABLE.iter().map(|entry| entry.section).collect();
        assert_eq!(
            STRATEGY_TABLE.len(),
            declared.len(),
            "a section is declared twice in STRATEGY_TABLE"
        );
        let missing: Vec<&str> = sections
            .iter()
            .map(String::as_str)
            .filter(|section| !declared.contains(section))
            .collect();
        assert!(missing.is_empty(), "sections with no strategy: {missing:?}");
        let extra: Vec<&str> = declared
            .iter()
            .copied()
            .filter(|section| !sections.contains(*section))
            .collect();
        assert!(extra.is_empty(), "strategies for no section: {extra:?}");
    }

    #[test]
    fn every_exception_names_its_attribution_rule_and_its_reason() {
        for entry in STRATEGY_TABLE {
            assert!(
                entry
                    .shape
                    .expected_combine_depth()
                    .contains(&entry.combine_depth),
                "`{}` declares combine depth {} for shape {}",
                entry.section,
                entry.combine_depth,
                entry.shape.as_str()
            );
            let concatenates = entry.shape == MergeShape::Concatenate;
            assert_eq!(
                concatenates,
                matches!(entry.rule, crate::provenance::AttributionRule::Concatenate),
                "`{}` must declare the concatenate rule exactly when it concatenates",
                entry.section
            );
            if !is_plain(entry.shape) {
                assert!(
                    !entry.note.is_empty(),
                    "`{}` is an exception and must name its attribution rule",
                    entry.section
                );
            }
        }
    }

    #[test]
    fn catalog_keys_are_the_serialized_spelling_of_the_schema_fields() {
        let keys = catalog_keys();
        assert_eq!(
            keys.len(),
            STRATEGY_TABLE.len(),
            "the sentinel must produce one key per declared section"
        );
        let renamed: Vec<&String> = keys
            .iter()
            .filter(|(key, section)| key.as_str() != section.as_str())
            .map(|(key, _)| key)
            .collect();
        assert_eq!(
            renamed,
            vec!["$schema"],
            "`$schema` is the only field whose serialized key differs from its name; \
             a second rename needs a reviewed mapping"
        );
    }
}
