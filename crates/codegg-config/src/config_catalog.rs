/// The exact first line of the generated catalog.
///
/// `scripts/check_config_provenance.py` requires it, character for character,
/// so a hand-edited file is rejected even when the rows happen to match.
pub(crate) const GENERATED_HEADER: &str =
    "<!-- AUTO-GENERATED by crates/codegg-config/src/config_catalog.rs — DO NOT EDIT -->";

/// The command that regenerates the catalog, quoted in its header.
pub(crate) const UPDATE_COMMAND: &str =
    "CODEGG_UPDATE_CONFIG_CATALOG=1 cargo test -p codegg-config config_catalog";

